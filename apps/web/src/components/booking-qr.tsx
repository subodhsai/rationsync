import QRCode from "qrcode";

/**
 * The booking token as a QR code, drawn on the server as SVG. The token is random and
 * carries no personal details; the shop's scanner looks it up through the API.
 */
export async function BookingQr({ token, label }: { token: string; label: string }) {
  const svg = await QRCode.toString(token, {
    type: "svg",
    margin: 2,
    errorCorrectionLevel: "M",
    color: { dark: "#182620", light: "#ffffff" },
  });
  return (
    <div
      role="img"
      aria-label={label}
      className="mx-auto aspect-square w-full max-w-60 rounded-lg border border-border bg-white p-2 [&>svg]:h-full [&>svg]:w-full"
      // Generated by the qrcode library from a hex token; contains no user input.
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}
